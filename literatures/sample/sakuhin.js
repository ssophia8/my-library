// 【文例】作品のファイル
//
// 作品ごとに 1 つ、このような形のファイルを literatures/ に置き、
// literatures/book.js の contents に名前を書きます。
// 本文は ` と ` のあいだに、そのまま書きます。
Kotoba.work({
  title: '作品の題',
  author: '作者名',          // 題のあとに、地付きで入ります（なければ消してかまいません）
  start: 'right',            // 右ページ（奇数ページ）からはじめる
  tobira: 'tobira.svg',      // 作品の前に入れる扉の画像（なければ消してかまいません）
  text: `
　ここに本文を書きます。一行が、ひとつの段落になります。段落のはじめは、全角の空白でひと文字下げてください。
　文章が長くなると、本は自動でページを増やし、次のページへ流れていきます。ページ数も自動でつきます。
　「かぎかっこ」や、――ダッシュ、……三点リーダーも、そのまま書けます。

　空行をひとつ入れると、本の中でも一行あきます。場面の変わり目などにどうぞ。
　このあたりからは、ページが次へ流れていくようすを見るための、つなぎの文章です。窓の外では、夕方の光が少しずつ色を変えていきます。机の上の紙は、まだ白いままです。
　書きはじめる前の時間には、言葉がまだどこにもありません。けれど、書かれるのを待っている言葉は、きっともうどこかにあるのだと思います。
　ペンを持ち、最初の一文字を置くと、そのあとを追うように次の文字がやってきます。行が増え、段落が増え、やがてページがめくられていきます。
`,
  signature: '署名',         // 文末に、地付きから一字上げで入ります（なければ消してかまいません）
});
